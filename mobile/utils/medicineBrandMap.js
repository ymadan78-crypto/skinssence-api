export function getBrandForMedicine(name, fallbackCompany = '') {
  if (fallbackCompany && fallbackCompany.trim()) return fallbackCompany.trim();
  if (!name) return 'Other';
  const clean = name.trim();
  if (MEDICINE_BRAND_MAP[clean]) return MEDICINE_BRAND_MAP[clean];
  
  const lower = clean.toLowerCase();
  for (const [k, v] of Object.entries(MEDICINE_BRAND_MAP)) {
    if (lower.includes(k.toLowerCase()) || k.toLowerCase().includes(lower)) {
      return v;
    }
  }

  // Regex patterns
  if (/screenguard|aquaedge|acnepurge|depiscreen|hebeda|kalsma|kezil|velmect|velnact/i.test(lower)) {
    return 'Velnourish';
  }
  if (/nidcort|nidgly|nidsoft|nidsone|nidtroin|tacronid|piranid|zithronid|efanid/i.test(lower)) {
    return 'Indus';
  }
  if (/cuticans|ethisun|kozilite|lipz|seren|sweatnil|trichospire|tyrodin/i.test(lower)) {
    return 'Ethicare / Ubik';
  }
  if (/sebogel|acnewar|clearzit|logifeel|z block/i.test(lower)) {
    return 'Canixa';
  }

  return 'Other';
}
